'use strict';
const assert = require('node:assert/strict');
const {selectActivities, videoTime} = require('../src/VehicleCounter.Api/wwwroot/activity.js');
const vehicles = Array.from({length:123}, (_, i) => ({trackId:i+1,vehicleClass:'car',firstSeenSeconds:i/10,crossed:i%3===0,direction:i%3===0?'A to B':null,crossedAtSeconds:i%3===0?i/10+1:null}));
const snapshot={id:'fixture',vehicles,events:[]};
const ids=[];
for(let page=0;page<3;page++)ids.push(...selectActivities(snapshot,'all',page).rows.map(row=>row.trackId));
assert.equal(new Set(ids).size,123);
assert.equal(ids.length,123);
console.log('PASS: Pagination retains every vehicle beyond the previous 100-row limit');
const crossed=selectActivities(snapshot,'crossed');
assert.equal(crossed.filteredTotal,41);
assert(crossed.rows.every(row=>row.crossed));
const waiting=selectActivities(snapshot,'not-crossed');
assert.equal(waiting.filteredTotal,82);
assert(waiting.rows.every(row=>!row.crossed));
console.log('PASS: Crossed and not-crossed filters retain the correct rows');
assert.equal(selectActivities(snapshot,'all',99).page,2);
assert.equal(selectActivities(snapshot,'all',99).rows.length,23);
console.log('PASS: Page number is clamped to the available rows');
const old=selectActivities({events:[{trackId:1,vehicleClass:'car',direction:'B to A',videoSeconds:1.25}]});
assert.equal(old.complete,false);
assert.equal(old.rows.length,1);
assert.equal(old.rows[0].firstSeenSeconds,null);
console.log('PASS: Older crossing-only results are identified without inventing detections');
assert.equal(videoTime(1.2012),'00:01.201');
assert.equal(videoTime(null),'—');
assert.equal(selectActivities({vehicles:[],events:[]}).filteredTotal,0);
console.log('PASS: Empty results and millisecond video times are handled');
const scrambled=[{trackId:10,firstSeenSeconds:0},{trackId:2,firstSeenSeconds:99},{trackId:1,firstSeenSeconds:4}];
assert.deepEqual(selectActivities({vehicles:scrambled}).rows.map(v=>v.trackId),[1,2,10]);
console.log('PASS: Track numbers sort numerically in ascending order');
